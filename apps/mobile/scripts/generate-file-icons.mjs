// Writes src/lib/files/file-icons.generated.ts: the part of material-icon-theme the phone ships.
// The web inlines all 1,238 icons (5 MB). The phone gets the icons that the names below resolve
// to, plus the generic file and folder icons, as SVG strings drawn with react-native-svg.
//
//   node apps/mobile/scripts/generate-file-icons.mjs
//
// Run it again after bumping material-icon-theme or editing the lists. The mapping uses the same
// resolver as the web (`@band-app/shared/file-icon-name`), so a listed name gets the web's icon.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const requireFromWeb = createRequire(join(here, "../../web/package.json"));
const themeDir = dirname(requireFromWeb.resolve("material-icon-theme/package.json"));
const manifest = JSON.parse(readFileSync(join(themeDir, "dist/material-icons.json"), "utf8"));

const EXTENSIONS = `ts tsx js jsx mjs cjs mts cts json jsonc md mdx css scss sass less html htm xml
  yaml yml toml py rs go java kt swift c h cpp hpp cs rb php sh bash zsh fish sql graphql gql vue
  svelte astro lock log txt env png jpg jpeg gif webp svg ico pdf zip gz tar csv ini lua dart ex
  exs prisma tf proto ipynb d.ts test.ts spec.ts test.tsx spec.tsx test.js spec.js stories.tsx
  mp4 mov mp3 wav woff woff2 ttf otf wasm patch diff`.split(/\s+/);
const FILE_NAMES = `package.json tsconfig.json dockerfile docker-compose.yml compose.yml .gitignore
  .gitattributes .env .env.local readme.md license license.md makefile cargo.toml cargo.lock
  pnpm-lock.yaml pnpm-workspace.yaml yarn.lock package-lock.json biome.json vite.config.ts
  vitest.config.ts .prettierrc .npmrc .nvmrc go.mod go.sum requirements.txt gemfile claude.md
  agents.md .editorconfig jest.config.js next.config.js tailwind.config.js .dockerignore deno.json
  bun.lockb app.json eas.json`.split(/\s+/);
const FOLDERS = `src lib dist build out node_modules test tests __tests__ docs public assets
  components scripts config .git .github .vscode packages apps api app utils hooks styles images
  types vendor target .band .claude e2e fixtures migrations models routes services pages
  screens store theme templates tools bin ios android`.split(/\s+/);

const pick = (map, keys) =>
  Object.fromEntries(keys.filter((k) => Object.hasOwn(map, k)).map((k) => [k, map[k]]));

const fileExtensions = pick(manifest.fileExtensions, EXTENSIONS);
const fileNames = pick(manifest.fileNames, FILE_NAMES);
const folderNames = pick(manifest.folderNames, FOLDERS);
const folderNamesExpanded = pick(manifest.folderNamesExpanded, FOLDERS);

const names = new Set([
  manifest.file,
  manifest.folder,
  manifest.folderExpanded,
  ...Object.values(fileExtensions),
  ...Object.values(fileNames),
  ...Object.values(folderNames),
  ...Object.values(folderNamesExpanded),
]);

const svg = {};
for (const name of [...names].sort()) {
  const def = manifest.iconDefinitions[name];
  if (!def) throw new Error(`no icon definition for ${name}`);
  svg[name] = readFileSync(join(themeDir, "dist", def.iconPath), "utf8")
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/>\s+</g, "><")
    .trim();
}

const out = `// Generated by scripts/generate-file-icons.mjs from material-icon-theme ${
  JSON.parse(readFileSync(join(themeDir, "package.json"), "utf8")).version
}. Do not edit.
import type { FileIconMaps } from "@band-app/shared/file-icon-name";

export const FILE_ICON_MAPS: FileIconMaps = ${JSON.stringify(
  {
    fileNames,
    fileExtensions,
    folderNames,
    folderNamesExpanded,
    file: manifest.file,
    folder: manifest.folder,
    folderExpanded: manifest.folderExpanded,
  },
  null,
  2,
)};

export const FILE_ICON_SVG: Readonly<Record<string, string>> = ${JSON.stringify(svg, null, 2)};
`;
writeFileSync(join(here, "../src/lib/files/file-icons.generated.ts"), out);
console.log(`${names.size} icons, ${(out.length / 1024).toFixed(0)} KB`);
